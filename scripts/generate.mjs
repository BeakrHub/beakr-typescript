// Generate the SDK's typed layer from the engine's documented public contract.
//
// Writes src/generated/{schema,operations}.ts (exported from src/index.ts) from
// docs/api/public-openapi.json, the only contract this package is built from:
// the hand-written resources build their requests with it too. Routes the API
// serves without documenting them are not in this package.
//
// Source, first match wins: the first CLI argument (a path or an http(s) URL),
// BEAKR_OPENAPI, then the committed contract in the engine checkout:
// $BEAKR_ENGINE_PATH, else a sibling ../beakr-engine, else this repository's
// committed snapshot
// snapshots/beakr-engine (docs/api/public-openapi.json; see
// scripts/refresh_snapshots.py).
//
// Usage: npm run generate [-- <public-path-or-url>]
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import { renderOperations } from "./operations.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const isUrl = (c) => /^https?:\/\//.test(c);

function findSource(candidates, what) {
  const source = candidates.filter(Boolean).find((c) => isUrl(c) || existsSync(c));
  if (!source) {
    console.error(`No ${what} OpenAPI document found. Pass a path or URL, or set the env variable.`);
    process.exit(1);
  }
  return source;
}

async function generate({ source, outDir, label }) {
  const input = isUrl(source) ? new URL(source) : new URL(`file://${resolve(source)}`);
  // A field with a default is optional to send: the server fills it in. With
  // openapi-typescript's default (defaultNonNullable: true) every defaulted field
  // became required in request types, so a caller had to spell out `role`,
  // `never_expires`, `ingest_to_wiki` and the like (audit C051). Optionality now
  // follows the contract's own `required` list, for requests and responses alike.
  const ast = await openapiTS(input, { defaultNonNullable: false });
  const header =
    `// Generated by scripts/generate.mjs from the Beakr ${label}. Do not edit.\n` +
    `// Source: ${isUrl(source) ? source : `docs/api/${source.split("/").pop()}`}\n\n`;
  const out = resolve(root, outDir, "schema.ts");
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, header + astToString(ast));
  console.log(`wrote ${out}`);

  // One typed method per operation, from the same document.
  const spec = isUrl(source)
    ? await (await fetch(source)).json()
    : JSON.parse(readFileSync(resolve(source), "utf8"));
  const { source: operationsSource, count, areas } = renderOperations(spec);
  const operationsOut = resolve(root, outDir, "operations.ts");
  writeFileSync(operationsOut, operationsSource);
  console.log(`wrote ${operationsOut} (${count} operations in ${areas} areas)`);
}

/** `docs/api/<file>` in $BEAKR_ENGINE_PATH, a sibling engine checkout, then the snapshot. */
function engineCandidates(file) {
  return [
    process.env.BEAKR_ENGINE_PATH && resolve(process.env.BEAKR_ENGINE_PATH, "docs/api", file),
    resolve(root, "../beakr-engine/docs/api", file),
    resolve(root, "snapshots/beakr-engine/docs/api", file),
  ];
}

await generate({
  source: findSource(
    [
      process.argv[2],
      process.env.BEAKR_OPENAPI,
      ...engineCandidates("public-openapi.json"),
    ],
    "public",
  ),
  outDir: "src/generated",
  label: "public OpenAPI document",
});
